/**
 * The pages that are text: buying guides, the shop's own story, the policies.
 *
 * Eleven links in the footer, three in the product family and one in the
 * account pointed at these and none of them existed. A footer with fourteen
 * dead links is worse than a footer with six live ones, and a shop whose
 * «حریم خصوصی» link 404s is a shop that cannot be published.
 *
 * PLACEHOLDER CONTENT, with one exception that matters: the privacy notice and
 * the terms of sale are legal documents. What is here is a plain, truthful
 * description of what this build actually does — it claims no certification
 * the shop has not been granted, and it does not describe processing that does
 * not happen. It still has to be reviewed by somebody qualified before the
 * shop takes real money, and the page says so.
 *
 * Structure over markup. A block is a heading and some paragraphs, and the
 * storefront decides what element each becomes. A content source that returned
 * HTML would be a content source that can put a `<script>` on every reader's
 * page.
 *
 * When the admin panel exists these are rows it owns, which is why they live
 * under `server/` and no component holds a copy.
 */
