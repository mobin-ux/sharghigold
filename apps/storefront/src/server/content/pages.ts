/**
 * Find a page by its slug within one family.
 *
 * `slug` comes from the URL, so it is arbitrary text. It is only ever compared
 * against slugs this module already holds — never used to build a path, read a
 * file, or index into anything — so an unknown or hostile value can do nothing
 * but miss, and the route answers 404.
 */
export function findPage(pages: readonly StaticPage[], slug: string): StaticPage | undefined {
  return pages.find((page) => page.slug === slug);
}
